/*
 * Load boot logo from boot disk for Loongson boards.
 * Detects boot device from bootcmd env, falls back to built-in logo.
 */

#include <common.h>
#include <env.h>
#include <errno.h>
#include <fs.h>
#include <splash.h>
#include <asm/global_data.h>

#ifdef CONFIG_VIDEO_LOGO
#include <bmp_logo.h>
#endif

DECLARE_GLOBAL_DATA_PTR;

#ifndef LOONGSON_LOGO_PATH
#define LOONGSON_LOGO_PATH	"/boot/logo.bmp"
#endif

static int load_builtin_logo(ulong addr)
{
#ifdef CONFIG_VIDEO_LOGO
	u32 logo_size;

	/*
	 * When CONFIG_DM_VIDEO=y, bmp_logo_bitmap is a complete BMP file
	 * generated by --gen-bmp. file_size is at offset 2, little-endian.
	 */
	logo_size = bmp_logo_bitmap[2] |
		    (bmp_logo_bitmap[3] << 8) |
		    (bmp_logo_bitmap[4] << 16) |
		    (bmp_logo_bitmap[5] << 24);

	memcpy((void *)addr, bmp_logo_bitmap, logo_size);
	return 0;
#else
	return -ENOSYS;
#endif
}

static int try_load_logo(const char *ifname, const char *devpart, ulong addr)
{
	loff_t bmp_size;
	loff_t actread;
	int ret;

	ret = fs_set_blk_dev(ifname, devpart, FS_TYPE_ANY);
	if (ret)
		return ret;

	ret = fs_size(LOONGSON_LOGO_PATH, &bmp_size);
	if (ret)
		return ret;

	if (addr + bmp_size >= gd->start_addr_sp)
		return -EFAULT;

	/* fs_size() implicitly calls fs_close(), reopen device */
	ret = fs_set_blk_dev(ifname, devpart, FS_TYPE_ANY);
	if (ret)
		return ret;

	ret = fs_read(LOONGSON_LOGO_PATH, addr, 0, 0, &actread);
	fs_close();

	if (!ret)
		printf("Logo loaded from %s %s " LOONGSON_LOGO_PATH " (%lld bytes)\n",
		       ifname, devpart, actread);

	return ret;
}

/*
 * Detect boot device from bootcmd's root= parameter.
 * e.g. root=/dev/mmcblk0p1 -> mmc 0:1
 *      root=/dev/mmcblk1p1 -> mmc 1:1
 *      root=/dev/sda1      -> scsi 0:1
 */
static int get_boot_device(char *ifname_buf, size_t ifname_sz, char *devpart_buf, size_t devpart_sz)
{
	char *bootcmd = env_get("bootcmd");
	char *p;
	char *syspart = env_get("syspart");
	const char *part = syspart ? syspart : "1";

	if (!bootcmd)
		return -1;

	p = strstr(bootcmd, "root=/dev/");
	if (!p)
		return -1;

	p += strlen("root=/dev/");

	if (strncmp(p, "mmcblk0p", 8) == 0) {
		strlcpy(ifname_buf, "mmc", ifname_sz);
		snprintf(devpart_buf, devpart_sz, "0:%s", part);
		return 0;
	}

	if (strncmp(p, "mmcblk1p", 8) == 0) {
		strlcpy(ifname_buf, "mmc", ifname_sz);
		snprintf(devpart_buf, devpart_sz, "1:%s", part);
		return 0;
	}

	if (strncmp(p, "sda", 3) == 0) {
		strlcpy(ifname_buf, "scsi", ifname_sz);
		snprintf(devpart_buf, devpart_sz, "0:%s", part);
		return 0;
	}

	return -1;
}

int splash_screen_prepare(void)
{
	char *splashimage;
	ulong bmp_load_addr;
	char boot_ifname[8];
	char boot_devpart[16];
	int ret;

	splashimage = env_get("splashimage");
	if (!splashimage)
		return -ENOENT;

	bmp_load_addr = hextoul(splashimage, 0);
	if (!bmp_load_addr) {
		printf("Error: bad splashimage address\n");
		return -EFAULT;
	}

	/* Detect boot device from bootcmd and try loading logo */
	if (!get_boot_device(boot_ifname, sizeof(boot_ifname), boot_devpart, sizeof(boot_devpart))) {
		printf("logo: boot device detected: %s %s\n",
		       boot_ifname, boot_devpart);

		/* Init storage if needed */
		if (!strcmp(boot_ifname, "scsi"))
			run_command("scsi reset", 0);
		else if (!strcmp(boot_ifname, "sata"))
			run_command("sata init", 0);
		else if (!strcmp(boot_ifname, "mmc"))
			run_command("mmc rescan", 0);
		else if (!strcmp(boot_ifname, "usb"))
			run_command("usb start", 0);

		ret = try_load_logo(boot_ifname, boot_devpart, bmp_load_addr);
		if (!ret)
			return 0;
	}

	/* Fall back to built-in U-Boot logo */
	printf("No " LOONGSON_LOGO_PATH " found on boot disk, using built-in logo\n");
	return load_builtin_logo(bmp_load_addr);
}
